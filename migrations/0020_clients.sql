-- Client folders (T6.40). A client groups albums; deleting a client unassigns
-- them (ON DELETE SET NULL), albums are never deleted with it. drizzle-kit
-- generated the table/index/column; the ON DELETE SET NULL on the ADD COLUMN
-- and the slug-namespace triggers at the end are manual (kept in sync by hand;
-- re-append after regenerating).
CREATE TABLE `clients` (
	`id` text PRIMARY KEY NOT NULL,
	`slug` text NOT NULL,
	`name` text NOT NULL,
	`default_mode` text DEFAULT 'proofing' NOT NULL,
	`default_show_on_home` integer DEFAULT false NOT NULL,
	`page_enabled` integer DEFAULT true NOT NULL,
	`created_at` text DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')) NOT NULL,
	CONSTRAINT "clients_slug_check" CHECK(length("clients"."slug") BETWEEN 1 AND 60 AND "clients"."slug" NOT GLOB '*[^a-z0-9-]*' AND "clients"."slug" NOT GLOB '-*' AND "clients"."slug" NOT GLOB '*-' AND "clients"."slug" NOT GLOB '*--*'),
	CONSTRAINT "clients_name_check" CHECK(length("clients"."name") BETWEEN 1 AND 120),
	CONSTRAINT "clients_default_mode_check" CHECK("clients"."default_mode" IN ('proofing','delivery')),
	CONSTRAINT "clients_default_show_on_home_check" CHECK("clients"."default_show_on_home" IN (0,1)),
	CONSTRAINT "clients_page_enabled_check" CHECK("clients"."page_enabled" IN (0,1))
);
