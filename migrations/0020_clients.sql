-- MANUAL BLOCK (not generated by drizzle-kit): one URL namespace. A client slug
-- and a gallery slug may never be equal, case-insensitively (`/<slug>` is one
-- route). The app checks both ways first (slug-namespace.ts); these triggers
-- catch races. Raised message: slug_taken. Own-slug updates do not collide:
-- the other table is the one searched, so the row itself never matches.
-- ---------------------------------------------------------------------------
CREATE TRIGGER `clients_slug_namespace_insert` BEFORE INSERT ON `clients`
WHEN EXISTS (SELECT 1 FROM `galleries` WHERE `slug` = NEW.`slug` COLLATE NOCASE)
BEGIN
	SELECT RAISE(ABORT, 'slug_taken');
END;
